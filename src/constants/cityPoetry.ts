export function getDayPhase(orbitHour: number, cityNameCN: string): DayPhase {
    const h = ((orbitHour % 24) + 24) % 24;
    const found = PHASES.findIndex((p) => h < p.until);
    const i = found === -1 ? PHASES.length - 1 : found;
    const lines = CITY_LINES[cityNameCN];
    return { label: PHASES[i].label, line: lines ? lines[i] : PHASES[i].line.replace('{city}', cityNameCN) };
}

/**
 * 获取同步事实
 * "你的身体时钟，与{城市}同步"
 */
export function getSyncStatement(cityNameCN: string): string {
    return `你的身体时钟，与${cityNameCN}同步`;
}
